#!/usr/bin/env python3
"""Build the 100-word banks and missing speech lines from the reviewed expansion."""
import argparse, hashlib, json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).with_name('vocabulary-expansion.json')
MODULE = ROOT / 'frontend-game/games/english_shared/vocabulary-100.js'
LINES = Path(__file__).with_name('speech-lines.json')
VERSION = '20260930v100'

def build():
    data = json.loads(SOURCE.read_text())
    original = (ROOT / 'frontend-game/games/english_shared/catalog.js').read_text()
    banks = {}
    for bank in ('animals', 'objects'):
        old = json.loads(re.search(r'export const ' + bank + r' = (\[.*?\]);', original).group(1))
        new = data[bank]
        assert len(old) == 30 and len(new) == 70
        assert len({x['id'] for x in old + new}) == 100
        assert len({x['word'] for x in old + new}) == 100
        assert all(re.fullmatch('[a-z0-9_]+', x['id']) for x in new)
        banks[bank] = [{k: v for k, v in x.items() if k != 'subject'} for x in new]
    module = "// Generated by scripts/english-learning/build-vocabulary-expansion.py.\n"
    module += "// The original 30 molds stay separate for Jelly Colors.\n"
    module += "import {animals as originalAnimals, objects as originalObjects, animalImage as originalImage} from './catalog.js?v=20260924e2';\n"
    module += 'const extraAnimals = ' + json.dumps(banks['animals'], ensure_ascii=False, indent=2) + ';\n'
    module += 'const extraObjects = ' + json.dumps(banks['objects'], ensure_ascii=False, indent=2) + ';\n'
    module += "export const animals = [...originalAnimals, ...extraAnimals];\n"
    module += "export const teddyObjects = [...originalObjects, ...extraObjects];\n"
    module += "export const animalImage = item => item.image ? originalImage(item) : new URL('../peekaboo_house/assets/animals/' + item.id + '-v1.webp', import.meta.url).href;\n"
    new_lines = []
    def add(ident, text, voice, scene, focus, instruction):
        new_lines.append(dict(id=ident, text=text, role=voice, voice_profile=voice,
            scene=scene, focus=focus, instruction=instruction, rate=.94,
            seed=int(hashlib.sha256(ident.encode()).hexdigest()[:4], 16)))
    for x in banks['animals']:
        word, ident = x['word'], x['id']
        noun = ('an ' if re.match('[aeiou]', word) else 'a ') + word
        add('where_' + ident, "Where's the " + word + '?', 'guide', 'question: find a hidden friend', word,
            '好奇活泼的童声，动物名称清晰重读，词间稍停顿，问句有期待感；只读英文。')
        add('lf_p_this_' + ident, 'This is ' + noun + '.', 'guide', 'discovery: identify the other animal', word,
            '亲切好奇的童声，动物名称清晰重读，慢一点帮助听懂，温柔不责备；只读英文。')
        add('lf_p_yes_' + ident, 'Yes! It is ' + noun + '!', 'guide', 'celebration: found the animal', word,
            '开心惊喜的童声，Yes雀跃上扬，动物名称突出重读，清晰舒缓；只读英文。')
    for x in banks['objects']:
        word, ident = x['word'], x['id']
        noun = x.get('quantifier', 'An' if re.match('[aeiou]', word) else 'A') + ' ' + word
        add('t_ask_' + ident, x.get('requestText', noun + ', please.'), 'teddy', 'request: bring Teddy a gift', word,
            '温柔小熊童声，期待又有礼，物品名重读略拉长，please轻轻上扬；只读英文。')
        add('lf_t_got_' + ident, x.get('thanksText', 'Yes! ' + noun + '! Thank you!'), 'teddy', 'thanks: celebrate the gift', word,
            '小熊童声开心雀跃，Yes惊喜，物品名重读，Thank you热情真诚；只读英文。')
    overrides = data.get('speech_overrides', {})
    assert set(overrides) <= {x['id'] for x in new_lines}
    for x in new_lines:
        settings = overrides.get(x['id'], {})
        assert set(settings) <= {'instruction', 'rate', 'seed'}
        x.update(settings)
        assert sum(1 if ord(c) < 128 else 2 for c in x['instruction']) <= 100
    existing = json.loads(LINES.read_text())
    generated = {x['id']: x for x in new_lines}
    old_ids = {x['id'] for x in existing}
    existing = [generated.get(x['id'], x) for x in existing]
    existing.extend(x for x in new_lines if x['id'] not in old_ids)
    assert len(new_lines) == 350
    return {MODULE: module, LINES: json.dumps(existing, ensure_ascii=False, indent=2) + '\n',
            Path(__file__).with_name('vocabulary-speech-lines.json'): json.dumps(new_lines, ensure_ascii=False, indent=2) + '\n'}

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = build()
    for path, text in outputs.items():
        if args.check:
            assert path.read_text() == text, 'Rebuild ' + str(path)
        else:
            path.write_text(text)
    print(('Checked' if args.check else 'Built') + ': 100 animals, 100 Teddy objects, 350 new speech clips')
